"""Build data/evaluation_queries.json from the human-authored data/evaluation_spec.json.

Relevance is defined by an *evidence snippet* that must occur in exactly one chunk of the named source. This script
chunks the sample documents with the same chunker/tokenizer settings the ingestion pipeline uses, resolves each snippet
to the stable memory ID (mem_<source-hash>_<chunk-index>) and writes a human-reviewable report.

    python backend/scripts/build_eval_labels.py            # (re)write data/evaluation_queries.json + docs/evaluation_label_review.md
    python backend/scripts/build_eval_labels.py --check    # verify the committed labels still match the samples

It never calls an external service. The tokenizer comes from the (locally cached) embedding model.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "backend"))

from app.common import sha256_hex  # noqa: E402
from app.config import Settings  # noqa: E402
from app.ingestion.chunker import chunk_text, normalize_text  # noqa: E402


def load_counter(model: str):
    from transformers import AutoTokenizer
    tok = AutoTokenizer.from_pretrained(model)
    return lambda text: len(tok.encode(text, add_special_tokens=False))


def chunk_sources(s: Settings, count) -> dict[str, list[dict]]:
    manifest = json.loads((ROOT / "data" / "samples" / "manifest.json").read_text())
    out: dict[str, list[dict]] = {}
    for items in manifest["sets"].values():
        for it in items:
            text = normalize_text((ROOT / "data" / "samples" / it["file"]).read_text(encoding="utf-8"))
            sid = "src_" + sha256_hex(text)[:12]
            chunks = chunk_text(text, count, s.chunk_max_tokens, s.chunk_overlap_tokens)
            out[it["source_name"]] = [{"memory_id": f"mem_{sid[4:]}_{c.index:04d}", "section": c.section, "text": c.text,
                                       "tokens": c.token_count} for c in chunks]
    return out


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    s = Settings(app_env="development")
    chunks = chunk_sources(s, load_counter(s.embedding_model))
    spec = json.loads((ROOT / "data" / "evaluation_spec.json").read_text())
    queries, errors = [], []
    review = ["# Evaluation label review", "",
              "Generated by `backend/scripts/build_eval_labels.py`. Each label below was resolved from a "
              "human-written evidence snippet; read the chunk text to confirm it really answers the query.", ""]
    for q in spec["queries"]:
        ids, evid = [], []
        review.append(f"### {q['query_id']} [{q['split']}] {q['query']}")
        for rel in q["relevant"]:
            hits = [c for c in chunks.get(rel["source"], []) if rel["evidence"] in c["text"]]
            if len(hits) != 1:
                errors.append(f"{q['query_id']}: evidence {rel['evidence']!r} matched {len(hits)} chunks in {rel['source']}")
                continue
            ids.append(hits[0]["memory_id"])
            evid.append(rel["evidence"])
            review.append(f"- **{rel['source']}** · `{hits[0]['memory_id']}` · section *{hits[0]['section']}*")
            review.append(f"  > {hits[0]['text'].replace(chr(10), ' ')[:400]}")
        review.append("")
        queries.append({"query_id": q["query_id"], "query": q["query"], "relevant_memory_ids": ids, "split": q["split"],
                        "tags": q["tags"], "evidence": evid})
    if errors:
        print("\n".join(errors), file=sys.stderr)
        return 1
    out = {"name": spec["name"], "description": spec["description"],
           "chunker": {"max_tokens": s.chunk_max_tokens, "overlap_tokens": s.chunk_overlap_tokens, "tokenizer": s.embedding_model},
           "label_provenance": "Evidence snippets written by hand; memory IDs resolved mechanically; every label printed to "
                               "docs/evaluation_label_review.md for manual inspection.",
           "queries": queries}
    target = ROOT / "data" / "evaluation_queries.json"
    if args.check:
        current = json.loads(target.read_text())
        if current["queries"] != queries:
            print("labels are out of date; run without --check", file=sys.stderr)
            return 2
        print(f"OK: {len(queries)} queries match the sample documents")
        return 0
    target.write_text(json.dumps(out, indent=1, ensure_ascii=False) + "\n")
    (ROOT / "docs" / "evaluation_label_review.md").write_text("\n".join(review) + "\n")
    print(f"wrote {len(queries)} queries -> {target.relative_to(ROOT)}")
    chunk_total = sum(len(v) for v in chunks.values())
    print(f"{chunk_total} chunks across {len(chunks)} sources; max chunk tokens {max(c['tokens'] for v in chunks.values() for c in v)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
