#!/usr/bin/env python3
"""Verify the frozen BEIR v1/v2 baselines against docs/baselines/beir_v1_v2_freeze.json (standard library only).

    python3 scripts/verify_baseline_hashes.py

Checks, with SHA-256:
  1. every file of the four official baseline runs under backend/artifacts/beir/   (v1 SciFact; v2 SciFact, NFCorpus, ArguAna)
  2. every file of backend/_baseline_src_v2/ against the `backend/app/...` hashes recorded at freeze time (the pre-phase-2 source snapshot)
Smoke runs listed in the manifest were never part of the baseline and are not committed; they are reported as skipped.
Live source under backend/app/ is NOT compared: it legitimately changed after the freeze (that is why the snapshot exists).
Exit status 0 only if every checked file exists and matches. Nothing is written or modified.
"""
from __future__ import annotations

import hashlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FREEZE = ROOT / "docs" / "baselines" / "beir_v1_v2_freeze.json"
ARTIFACTS = ROOT / "backend" / "artifacts" / "beir"
SNAPSHOT = ROOT / "backend" / "_baseline_src_v2"
SMOKE_MARKERS = ("beir_2026",)  # run ids generated by --query-limit smoke runs (timestamped), excluded from the baseline


def sha256(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def main() -> int:
    if not FREEZE.exists():
        print(f"missing {FREEZE}")
        return 2
    fz = json.loads(FREEZE.read_text())
    checked = bad = 0
    skipped_runs = []
    for run, files in fz["artifact_hashes"].items():
        if any(m in run.split("/")[-1] for m in SMOKE_MARKERS):
            skipped_runs.append(run)
            continue
        for name, want in files.items():
            p = ARTIFACTS / run / name
            checked += 1
            if not p.exists():
                bad += 1
                print(f"MISSING  artifacts/beir/{run}/{name}")
            elif sha256(p) != want:
                bad += 1
                print(f"CHANGED  artifacts/beir/{run}/{name}")
    art_checked = checked
    for key, want in fz["source_hashes"].items():
        if not key.startswith("backend/app/"):
            continue
        p = SNAPSHOT / key[len("backend/app/"):]
        checked += 1
        if not p.exists():
            bad += 1
            print(f"MISSING  _baseline_src_v2/{key[len('backend/app/'):]}")
        elif sha256(p) != want:
            bad += 1
            print(f"CHANGED  _baseline_src_v2/{key[len('backend/app/'):]}")
    print(f"{art_checked} baseline artifact files and {checked - art_checked} snapshot source files checked; {bad} problem(s)")
    if skipped_runs:
        print("skipped (smoke runs, intentionally not part of the baseline): " + ", ".join(skipped_runs))
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
