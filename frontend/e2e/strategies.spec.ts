  for (const n of ["Global dense", "Fixed graph", "Progressive expansion", "Soft graph routing"]) await expect(quality).toContainText(n)
  await expect(page.getByTestId("group-status")).toContainText(/confirmatory|exploratory|internal partition|development/)
