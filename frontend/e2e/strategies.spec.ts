  await expect(page.getByTestId("explanation")).toBeVisible()
  await expect(page.getByRole("table", { name: "Efficiency by strategy" })).toBeVisible()
  await expect(page.getByRole("link", { name: /JSON/ }).first()).toHaveAttribute("href", /strategies\/runs\/.+\/export\?format=json/)
  const list = page.getByRole("list", { name: "Per-query results" })
